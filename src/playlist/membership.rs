use crate::{
    playlist::{
        manager::PlaylistError, Playlist, PlaylistEpisode, PlaylistId, PlaylistType, SmartFilter,
        SmartPlaylistRule,
    },
    podcast::{Episode, Podcast},
    storage::{EpisodeId, PodcastId, Storage},
};
use chrono::{DateTime, Duration, Utc};
use std::collections::{HashMap, HashSet};

#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct EpisodeKey {
    pub podcast_id: PodcastId,
    pub episode_id: EpisodeId,
}

impl EpisodeKey {
    pub fn new(podcast_id: PodcastId, episode_id: EpisodeId) -> Self {
        Self {
            podcast_id,
            episode_id,
        }
    }

    pub fn from_episode(episode: &Episode) -> Self {
        Self::new(episode.podcast_id.clone(), episode.id.clone())
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PlaylistMembershipKind {
    Manual,
    Auto,
    Smart,
}

#[derive(Clone, Debug)]
pub struct PlaylistSummary {
    pub id: PlaylistId,
    pub name: String,
    pub kind: PlaylistMembershipKind,
    pub effective_episode_count: usize,
}

#[derive(Clone, Debug)]
pub struct PlaylistMembershipSnapshot {
    pub playlists: Vec<PlaylistSummary>,
    pub by_episode: HashMap<EpisodeKey, Vec<PlaylistId>>,
    pub evaluated_at: DateTime<Utc>,
    pub next_dynamic_change: Option<DateTime<Utc>>,
}

impl PlaylistMembershipSnapshot {
    pub fn count_for(&self, key: &EpisodeKey) -> usize {
        self.by_episode.get(key).map_or(0, Vec::len)
    }

    pub fn playlists_for(&self, key: &EpisodeKey) -> Vec<&PlaylistSummary> {
        let Some(ids) = self.by_episode.get(key) else {
            return Vec::new();
        };
        self.playlists
            .iter()
            .filter(|playlist| ids.contains(&playlist.id))
            .collect()
    }
}

#[derive(Clone, Debug)]
pub struct PlaylistEvaluationInputs {
    pub podcasts: Vec<Podcast>,
    pub episodes: Vec<Episode>,
}

#[derive(Clone, Debug)]
pub struct PlaylistMembershipBuild {
    pub snapshot: PlaylistMembershipSnapshot,
    pub smart_episodes: HashMap<PlaylistId, Vec<PlaylistEpisode>>,
}

pub async fn load_playlist_evaluation_inputs<S: Storage + ?Sized>(
    storage: &S,
    playlists: &[Playlist],
) -> Result<PlaylistEvaluationInputs, PlaylistError> {
    if !playlists
        .iter()
        .any(|playlist| playlist.smart_rules.is_some())
    {
        return Ok(PlaylistEvaluationInputs {
            podcasts: Vec::new(),
            episodes: Vec::new(),
        });
    }

    let podcast_ids = storage
        .list_podcasts()
        .await
        .map_err(|error| PlaylistError::Storage(format!("Could not list podcasts: {error}")))?;
    let mut inputs = PlaylistEvaluationInputs {
        podcasts: Vec::with_capacity(podcast_ids.len()),
        episodes: Vec::new(),
    };

    for podcast_id in podcast_ids {
        let podcast = storage.load_podcast(&podcast_id).await.map_err(|error| {
            PlaylistError::Storage(format!("Could not load podcast '{podcast_id}': {error}"))
        })?;
        let episodes = storage.load_episodes(&podcast_id).await.map_err(|error| {
            PlaylistError::Storage(format!(
                "Could not load episodes for podcast '{podcast_id}': {error}"
            ))
        })?;
        inputs.podcasts.push(podcast);
        inputs.episodes.extend(episodes);
    }

    Ok(inputs)
}

pub fn build_playlist_membership(
    playlists: &[Playlist],
    inputs: &PlaylistEvaluationInputs,
    detail_playlist_ids: &HashSet<PlaylistId>,
    now: DateTime<Utc>,
) -> PlaylistMembershipBuild {
    let mut by_episode: HashMap<EpisodeKey, Vec<PlaylistId>> = HashMap::new();
    let mut summaries = Vec::with_capacity(playlists.len());
    let mut smart_episodes = HashMap::new();
    let mut next_dynamic_change = None;

    for playlist in playlists {
        let (kind, episodes): (PlaylistMembershipKind, Vec<PlaylistEpisode>) =
            if let Some(rule) = &playlist.smart_rules {
                next_dynamic_change =
                    earliest_rule_change(rule, &inputs.episodes, now, next_dynamic_change);
                let evaluated = evaluate_smart_rule(rule, inputs, now);
                if detail_playlist_ids.contains(&playlist.id) {
                    smart_episodes.insert(playlist.id.clone(), evaluated.clone());
                }
                (PlaylistMembershipKind::Smart, evaluated)
            } else {
                let kind = match &playlist.playlist_type {
                    PlaylistType::AutoGenerated { .. } => PlaylistMembershipKind::Auto,
                    PlaylistType::User => PlaylistMembershipKind::Manual,
                };
                (kind, playlist.episodes.clone())
            };

        let mut unique_episodes = HashSet::with_capacity(episodes.len());
        for episode in &episodes {
            let key = EpisodeKey::new(episode.podcast_id.clone(), episode.episode_id.clone());
            if unique_episodes.insert(key.clone()) {
                by_episode.entry(key).or_default().push(playlist.id.clone());
            }
        }

        summaries.push(PlaylistSummary {
            id: playlist.id.clone(),
            name: playlist.name.clone(),
            kind,
            effective_episode_count: unique_episodes.len(),
        });
    }

    summaries.sort_by(|left, right| {
        let left_auto = left.kind == PlaylistMembershipKind::Auto;
        let right_auto = right.kind == PlaylistMembershipKind::Auto;
        right_auto
            .cmp(&left_auto)
            .then_with(|| left.name.to_lowercase().cmp(&right.name.to_lowercase()))
            .then_with(|| left.id.to_string().cmp(&right.id.to_string()))
    });

    PlaylistMembershipBuild {
        snapshot: PlaylistMembershipSnapshot {
            playlists: summaries,
            by_episode,
            evaluated_at: now,
            next_dynamic_change,
        },
        smart_episodes,
    }
}

pub fn evaluate_smart_rule(
    rule: &SmartPlaylistRule,
    inputs: &PlaylistEvaluationInputs,
    now: DateTime<Utc>,
) -> Vec<PlaylistEpisode> {
    rule.evaluate_at(&inputs.episodes, &inputs.podcasts, now)
        .into_iter()
        .enumerate()
        .map(|(index, episode)| PlaylistEpisode {
            podcast_id: episode.podcast_id.clone(),
            episode_id: episode.id.clone(),
            episode_title: Some(episode.title.clone()),
            added_at: now,
            order: index + 1,
            file_synced: false,
            filename: None,
        })
        .collect()
}

fn earliest_rule_change(
    rule: &SmartPlaylistRule,
    episodes: &[Episode],
    now: DateTime<Utc>,
    earliest: Option<DateTime<Utc>>,
) -> Option<DateTime<Utc>> {
    let mut next = earliest;
    for episode in episodes {
        next = earliest_filter_change(&rule.filter, episode.published, now, next);
    }
    next
}

fn earliest_filter_change(
    filter: &SmartFilter,
    published: DateTime<Utc>,
    now: DateTime<Utc>,
    earliest: Option<DateTime<Utc>>,
) -> Option<DateTime<Utc>> {
    match filter {
        SmartFilter::NewerThan(days) => published
            .checked_add_signed(Duration::days(i64::from(*days)))
            .filter(|expiration| *expiration >= now)
            .map(|expiration| earliest.map_or(expiration, |current| current.min(expiration)))
            .or(earliest),
        SmartFilter::And(filters) | SmartFilter::Or(filters) => {
            filters.iter().fold(earliest, |current, nested| {
                earliest_filter_change(nested, published, now, current)
            })
        }
        _ => earliest,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{
        playlist::{Playlist, RefreshPolicy, SmartFilter},
        podcast::EpisodeStatus,
    };
    use chrono::TimeZone;

    fn make_episode(podcast_id: &PodcastId, published: DateTime<Utc>, title: &str) -> Episode {
        Episode::new(
            podcast_id.clone(),
            title.to_string(),
            "https://example.com/audio.mp3".to_string(),
            published,
        )
    }

    fn playlist(
        name: &str,
        playlist_type: PlaylistType,
        episodes: Vec<PlaylistEpisode>,
        smart_rules: Option<SmartPlaylistRule>,
    ) -> Playlist {
        Playlist {
            id: PlaylistId::new(),
            name: name.to_string(),
            description: None,
            playlist_type,
            episodes,
            created: Utc::now(),
            last_updated: Utc::now(),
            smart_rules,
        }
    }

    fn reference(podcast_id: &PodcastId, episode_id: &EpisodeId) -> PlaylistEpisode {
        PlaylistEpisode {
            podcast_id: podcast_id.clone(),
            episode_id: episode_id.clone(),
            episode_title: None,
            added_at: Utc::now(),
            order: 1,
            file_synced: false,
            filename: None,
        }
    }

    #[test]
    fn test_playlist_membership_indexes_manual_auto_and_limited_smart_playlists() {
        let now = Utc.with_ymd_and_hms(2026, 11, 6, 12, 0, 0).unwrap();
        let podcast_id = PodcastId::new();
        let older = make_episode(&podcast_id, now - Duration::days(2), "Older");
        let newer = make_episode(&podcast_id, now - Duration::days(1), "Newer");
        let manual = playlist(
            "Manual",
            PlaylistType::User,
            vec![
                reference(&podcast_id, &older.id),
                reference(&podcast_id, &older.id),
            ],
            None,
        );
        let today = playlist(
            "Today",
            PlaylistType::AutoGenerated {
                generator: crate::playlist::AutoPlaylistKind::Today,
                refresh_policy: RefreshPolicy::Daily,
                last_refreshed: None,
            },
            vec![reference(&podcast_id, &older.id)],
            None,
        );
        let smart = playlist(
            "Recent",
            PlaylistType::User,
            Vec::new(),
            Some(SmartPlaylistRule {
                filter: SmartFilter::Unplayed,
                sort: Some(crate::playlist::SmartSort {
                    field: crate::playlist::SmartSortField::Date,
                    direction: crate::playlist::SmartSortDirection::Descending,
                }),
                limit: Some(1),
            }),
        );
        let inputs = PlaylistEvaluationInputs {
            podcasts: Vec::new(),
            episodes: vec![older.clone(), newer.clone()],
        };
        let details = HashSet::from([smart.id.clone()]);

        let build = build_playlist_membership(
            &[manual.clone(), today.clone(), smart.clone()],
            &inputs,
            &details,
            now,
        );

        assert_eq!(
            build.snapshot.count_for(&EpisodeKey::from_episode(&older)),
            2
        );
        assert_eq!(
            build.snapshot.count_for(&EpisodeKey::from_episode(&newer)),
            1
        );
        assert_eq!(
            build
                .snapshot
                .playlists_for(&EpisodeKey::from_episode(&older))[0]
                .kind,
            PlaylistMembershipKind::Auto
        );
        assert_eq!(build.smart_episodes[&smart.id][0].episode_id, newer.id);
        assert_eq!(
            build.snapshot.playlists[0].kind,
            PlaylistMembershipKind::Auto
        );
    }

    #[test]
    fn test_playlist_membership_key_includes_podcast_id() {
        let now = Utc::now();
        let first_podcast = PodcastId::new();
        let second_podcast = PodcastId::new();
        let shared_episode_id = EpisodeId::new();
        let mut first = reference(&first_podcast, &shared_episode_id);
        first.podcast_id = first_podcast.clone();
        let manual = playlist("Manual", PlaylistType::User, vec![first], None);
        let inputs = PlaylistEvaluationInputs {
            podcasts: Vec::new(),
            episodes: Vec::new(),
        };
        let build = build_playlist_membership(&[manual], &inputs, &HashSet::new(), now);

        assert_eq!(
            build
                .snapshot
                .count_for(&EpisodeKey::new(first_podcast, shared_episode_id.clone())),
            1
        );
        assert_eq!(
            build
                .snapshot
                .count_for(&EpisodeKey::new(second_podcast, shared_episode_id)),
            0
        );
    }

    #[test]
    fn test_newer_than_boundary_is_inclusive_and_expires_after() {
        let published = Utc.with_ymd_and_hms(2026, 11, 1, 12, 0, 0).unwrap();
        let expiration = published + Duration::days(5);
        let podcast_id = PodcastId::new();
        let episode = make_episode(&podcast_id, published, "Boundary");
        let filter = SmartFilter::NewerThan(5);

        assert!(filter.matches_at(&episode, &[], expiration - Duration::nanoseconds(1)));
        assert!(filter.matches_at(&episode, &[], expiration));
        assert!(!filter.matches_at(&episode, &[], expiration + Duration::nanoseconds(1)));
    }

    #[test]
    fn test_newer_than_boundary_is_recorded_until_strictly_expired() {
        let now = Utc.with_ymd_and_hms(2026, 11, 6, 12, 0, 0).unwrap();
        let podcast_id = PodcastId::new();
        let episode = make_episode(&podcast_id, now - Duration::days(5), "Boundary");
        let smart = playlist(
            "Recent",
            PlaylistType::User,
            Vec::new(),
            Some(SmartPlaylistRule::new(SmartFilter::NewerThan(5))),
        );
        let inputs = PlaylistEvaluationInputs {
            podcasts: Vec::new(),
            episodes: vec![episode.clone()],
        };

        let at_boundary =
            build_playlist_membership(&[smart.clone()], &inputs, &HashSet::new(), now);
        assert_eq!(at_boundary.snapshot.next_dynamic_change, Some(now));
        assert_eq!(
            at_boundary
                .snapshot
                .count_for(&EpisodeKey::from_episode(&episode)),
            1
        );

        let after_boundary = build_playlist_membership(
            &[smart],
            &inputs,
            &HashSet::new(),
            now + Duration::nanoseconds(1),
        );
        assert_eq!(after_boundary.snapshot.next_dynamic_change, None);
        assert_eq!(
            after_boundary
                .snapshot
                .count_for(&EpisodeKey::from_episode(&episode)),
            0
        );
    }

    #[test]
    fn test_smart_playlist_sort_and_zero_limit_match_displayed_rows() {
        let now = Utc::now();
        let podcast_id = PodcastId::new();
        let mut played = make_episode(&podcast_id, now, "Played");
        played.status = EpisodeStatus::Played;
        let older = make_episode(&podcast_id, now - Duration::days(1), "Older");
        let inputs = PlaylistEvaluationInputs {
            podcasts: Vec::new(),
            episodes: vec![older, played],
        };
        let rule = SmartPlaylistRule {
            filter: SmartFilter::Or(vec![SmartFilter::Played, SmartFilter::Unplayed]),
            sort: Some(crate::playlist::SmartSort {
                field: crate::playlist::SmartSortField::Title,
                direction: crate::playlist::SmartSortDirection::Ascending,
            }),
            limit: Some(0),
        };

        assert!(evaluate_smart_rule(&rule, &inputs, now).is_empty());
    }
}
